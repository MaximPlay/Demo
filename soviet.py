    async def client_ready(self, client, db):
        self._db = db
        self._client = client
        if self.config["auto_mode"]:
            self.auto_task = asyncio.create_task(self._auto_reminder())

    async def on_unload(self):
        if hasattr(self, "auto_task"):
            self.auto_task.cancel()

