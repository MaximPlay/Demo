    @loader.command(ru_doc="— Сгенерировать пятилетний план для чата")
    async def plancmd(self, message):
        """Сгенерировать пятилетний план развития чата"""
        chat = await message.get_chat()
        chat_name = chat.title if hasattr(chat, 'title') else "Текущий"
        
        # Генерируем "реалистичные" квоты
        msg_quota = random.randint(100, 500)
        meme_quota = random.randint(5, 30)
        
        # Форматируем дату по-советски
        now = datetime.now()
        date_str = f"{now.day:02d}.{now.month:02d}.{now.year} г."
        
        await utils.answer(
            message,
            self.strings["plan_generated"].format(
                chat_name=chat_name,
                date=date_str,
                msg_quota=msg_quota,
                meme_quota=meme_quota
            )
        )

    async def watcher(self, message):
        """Автоматические реакции на сообщения"""
        if not self.config["auto_mode"]:
            return
        
        # 5% шанс среагировать на сообщение
        if random.random() < 0.05 and message.text:
            reactions = [
                "Одобряем инициативу!",
                "Записываем в протокол.",
                "Рекомендуем к тиражированию.",
                "Требует доработки, но в целом правильно.",
                "Отметить в приказе.",
            ]
            
            # Ставим реакцию или отвечаем
            try:
                if hasattr(message, 'react'):
                    await message.react('👍')
                await message.reply(random.choice(reactions))
            except Exception:
                pass
